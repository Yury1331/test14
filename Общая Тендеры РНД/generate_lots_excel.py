def fmt_money(value):
    if value is None:
        return "—"
    return value


def build_workbook():
    wb = Workbook()
    ws = wb.active
    ws.title = "Реестр лотов"

    header_fill = PatternFill("solid", fgColor="1F4E79")
    header_font = Font(color="FFFFFF", bold=True)

    ws.append(HEADERS)
    for col in range(1, len(HEADERS) + 1):
        cell = ws.cell(row=1, column=col)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")

    for i, lot in enumerate(LOTS, start=1):
        reg = lot["reg"]
        url = link(lot["type"], reg)
        search_url = SEARCH + reg
        row = [
            i,
            lot["region_scope"],
            lot["category"],
            reg,
            lot["procedure"],
            lot["customer"],
            lot["subject"],
            lot.get("description_extended", ""),
            fmt_money(lot["nmck"]),
            fmt_money(lot["contract_price"]),
            lot["status"],
            lot["platform"],
            lot["deadline"],
            url,
            search_url,
        ]
        ws.append(row)
        r = ws.max_row
        link_cell = ws.cell(row=r, column=14)
        link_cell.hyperlink = url
        link_cell.value = url
        link_cell.font = Font(color="0563C1", underline="single")
        search_cell = ws.cell(row=r, column=15)
        search_cell.hyperlink = search_url
        search_cell.value = search_url
        search_cell.font = Font(color="0563C1", underline="single")

    widths = [5, 22, 28, 22, 22, 34, 52, 60, 14, 14, 28, 16, 14, 50, 50]
    for idx, width in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(idx)].width = width

    for row in ws.iter_rows(min_row=2, max_row=ws.max_row):
        for cell in row:
            cell.alignment = Alignment(wrap_text=True, vertical="top")

    ws.freeze_panes = "A2"
    ws.auto_filter.ref = ws.dimensions
    return wb


