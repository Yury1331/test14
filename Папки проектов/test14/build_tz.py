FONT_CELL = Font(name="Calibri", size=10)
WRAP = Alignment(wrap_text=True, vertical="center")


def _set_col_widths(ws: Worksheet, widths: list[float]) -> None:
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w


def _header_row(ws: Worksheet, row: int, values: list[str]) -> None:
    for col, val in enumerate(values, 1):
        cell = ws.cell(row, col, val)
        cell.fill = FILL_HEAD
        cell.font = FONT_HEAD
        cell.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
        cell.border = THIN
    ws.row_dimensions[row].height = 32


def _title(ws: Worksheet, text: str, cols: int) -> None:
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=cols)
    cell = ws.cell(1, 1, text)
    cell.fill = FILL_TITLE
    cell.font = FONT_TITLE
    cell.alignment = Alignment(wrap_text=True, vertical="center")
    ws.row_dimensions[1].height = 28
    ws.freeze_panes = "A3"
    ws.auto_filter.ref = None
    ws.sheet_view.showGridLines = False
    ws.page_setup.orientation = "landscape"
    ws.page_setup.fitToPage = True
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0
    ws.page_setup.paperSize = ws.PAPERSIZE_A4
    ws.print_title_rows = "1:2"
    ws.oddFooter.right.text = "Стр. &P из &N"


def _data_row(ws: Worksheet, row: int, values: list, money_cols: set[int] | None = None) -> None:
    money_cols = money_cols or set()
    for col, val in enumerate(values, 1):
        cell = ws.cell(row, col, val)
        cell.font = FONT_CELL
        cell.alignment = WRAP
        cell.border = THIN
        if row % 2 == 0:
            cell.fill = FILL_ALT
        if col in money_cols and isinstance(val, (int, float)):
            cell.number_format = "#,##0.00"
            cell.alignment = Alignment(vertical="center", horizontal="right")
    ws.row_dimensions[row].height = 32


